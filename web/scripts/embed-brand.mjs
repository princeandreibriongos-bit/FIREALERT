import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const logo = fs.readFileSync(path.join(root, "public/brand/bfp-makati-logo.jpg"));
const bg = fs.readFileSync(path.join(root, "public/brand/station-bg.jpg"));

const out = `/** Auto-generated by scripts/embed-brand.mjs — do not edit by hand. */
export const LOGO_DATA_URL =
  "data:image/jpeg;base64,${logo.toString("base64")}";

export const STATION_BG_DATA_URL =
  "data:image/jpeg;base64,${bg.toString("base64")}";
`;

fs.writeFileSync(path.join(root, "lib/brand-assets.ts"), out);
console.log("embedded logo", logo.length, "bg", bg.length);
